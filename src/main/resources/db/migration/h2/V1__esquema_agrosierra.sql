CREATE TABLE rol (
    nombre VARCHAR(40) PRIMARY KEY,
    edita_todas BOOLEAN DEFAULT FALSE NOT NULL
);
CREATE TABLE rol_privilegio (
    rol_nombre VARCHAR(40) NOT NULL REFERENCES rol(nombre),
    privilegio VARCHAR(40) NOT NULL,
    PRIMARY KEY (rol_nombre, privilegio)
);
CREATE TABLE usuario (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    usuario VARCHAR(50) NOT NULL UNIQUE,
    contrasena VARCHAR(100) NOT NULL,
    nombre VARCHAR(120) NOT NULL,
    rol_nombre VARCHAR(40) NOT NULL REFERENCES rol(nombre),
    activo BOOLEAN DEFAULT TRUE NOT NULL
);
CREATE TABLE lote (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    codigo VARCHAR(30) NOT NULL UNIQUE,
    nombre VARCHAR(120) NOT NULL,
    hectareas DOUBLE PRECISION NOT NULL CHECK (hectareas > 0),
    cultivo VARCHAR(80) NOT NULL,
    valle VARCHAR(80) NOT NULL,
    campania_cerrada BOOLEAN DEFAULT FALSE NOT NULL,
    dosis_maxima_por_hectarea DOUBLE PRECISION NOT NULL CHECK (dosis_maxima_por_hectarea > 0)
);
CREATE TABLE labor (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    lote_id BIGINT NOT NULL REFERENCES lote(id),
    tipo VARCHAR(20) NOT NULL CHECK (tipo IN ('RIEGO','FUMIGACION','COSECHA')),
    fecha DATE NOT NULL,
    responsable_id BIGINT NOT NULL REFERENCES usuario(id),
    cantidad DOUBLE PRECISION NOT NULL CHECK (cantidad > 0),
    observacion VARCHAR(1000),
    creado_en TIMESTAMP(6) WITH TIME ZONE NOT NULL,
    clave_cliente VARCHAR(100),
    CONSTRAINT uk_labor_cliente UNIQUE (responsable_id, clave_cliente)
);
CREATE INDEX ix_labor_lote_fecha ON labor(lote_id, fecha DESC, id DESC);
CREATE INDEX ix_lote_valle_estado ON lote(valle, campania_cerrada);
