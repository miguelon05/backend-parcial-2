CREATE TABLE rol (
    nombre VARCHAR2(40) PRIMARY KEY,
    edita_todas NUMBER(1) DEFAULT 0 NOT NULL CHECK (edita_todas IN (0,1))
);
CREATE TABLE rol_privilegio (
    rol_nombre VARCHAR2(40) NOT NULL REFERENCES rol(nombre),
    privilegio VARCHAR2(40) NOT NULL,
    PRIMARY KEY (rol_nombre, privilegio)
);
CREATE TABLE usuario (
    id NUMBER(19) GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    usuario VARCHAR2(50) NOT NULL UNIQUE,
    contrasena VARCHAR2(100) NOT NULL,
    nombre VARCHAR2(120) NOT NULL,
    rol_nombre VARCHAR2(40) NOT NULL REFERENCES rol(nombre),
    activo NUMBER(1) DEFAULT 1 NOT NULL CHECK (activo IN (0,1))
);
CREATE TABLE lote (
    id NUMBER(19) GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    codigo VARCHAR2(30) NOT NULL UNIQUE,
    nombre VARCHAR2(120) NOT NULL,
    hectareas BINARY_DOUBLE NOT NULL CHECK (hectareas > 0),
    cultivo VARCHAR2(80) NOT NULL,
    valle VARCHAR2(80) NOT NULL,
    campania_cerrada NUMBER(1) DEFAULT 0 NOT NULL CHECK (campania_cerrada IN (0,1)),
    dosis_maxima_por_hectarea BINARY_DOUBLE NOT NULL CHECK (dosis_maxima_por_hectarea > 0)
);
CREATE TABLE labor (
    id NUMBER(19) GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    lote_id NUMBER(19) NOT NULL REFERENCES lote(id),
    tipo VARCHAR2(20) NOT NULL CHECK (tipo IN ('RIEGO','FUMIGACION','COSECHA')),
    fecha DATE NOT NULL,
    responsable_id NUMBER(19) NOT NULL REFERENCES usuario(id),
    cantidad BINARY_DOUBLE NOT NULL CHECK (cantidad > 0),
    observacion VARCHAR2(1000),
    creado_en TIMESTAMP(6) WITH TIME ZONE NOT NULL,
    clave_cliente VARCHAR2(100),
    CONSTRAINT uk_labor_cliente UNIQUE (responsable_id, clave_cliente)
);
CREATE INDEX ix_labor_lote_fecha ON labor(lote_id, fecha DESC, id DESC);
CREATE INDEX ix_lote_valle_estado ON lote(valle, campania_cerrada);
